from playwright.sync_api import sync_playwright

with sync_playwright() as p:
    browser = p.chromium.launch()
    page = browser.new_page()
    page.goto("https://playwright.dev")
    
    page.wait_for_load_state()  # добавлено: ожидание полной загрузки страницы
    
    title = page.title()
    
    # изменено: проверка вместо print (если слова нет, тест упадет с ошибкой)
    assert "Playwright" in title, f"Ожидалось 'Playwright' в заголовке, получено: {title}" 
    
    print("Тест пройден! Заголовок содержит 'Playwright'.") # добавлено для наглядности
    browser.close()